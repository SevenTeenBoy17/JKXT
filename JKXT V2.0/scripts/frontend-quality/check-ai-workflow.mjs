import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};vm.runInNewContext(fs.readFileSync('src/ai-workflow.js','utf8'),context);
const w=context.window.JKXTAiWorkflow;
const task={id:'task-B',status:'draft',uploads:[{id:'u',kind:'exam',sha256:'hash'}]};
const clone=x=>JSON.parse(JSON.stringify(x));
const result={status:'succeeded',fallback:false,solverAuthority:'OR_TOOLS',policyId:'policy-immutable',dsl:{hard:[],soft:[]}};
let calls=[];const api={get:async(p)=>{calls.push(p);return clone(task);},post:async(p,b)=>{calls.push(p);if(p.endsWith('/validate')){task.status='ready';return {status:'ready',uploads:clone(task.uploads),report:{counts:{error:0},severity:'pass'}};}if(p.endsWith('/parse'))return result;assert.equal(b.policyId,'policy-immutable');assert.deepEqual(clone(b.reviewedUploads),task.uploads);return {jobId:'job-B'};}};
assert.equal(w.mutable({...task,publishedAt:'now'}),false);
assert.equal(w.mutable({...task,status:'scheduling'}),false);
assert.throws(()=>w.realResponse({...result,fallback:true}));
await assert.rejects(w.prepare({},api),/选择/);
const p=await w.prepare({taskId:'task-B',text:'均衡',provider:'aliyun'},api);
assert.equal(calls.some(c=>c.includes('uploads')),false);
assert.equal(calls.some(c=>c.endsWith('schedule-jobs')),false);
const h=await w.submit(p,api);assert.equal(h.jobId,'job-B');assert.equal(h.taskId,'task-B');
assert.deepEqual(calls.slice(-3),['/exam-tasks/task-B','/exam-tasks/task-B/imports/validate','/exam-tasks/task-B/schedule-jobs']);
task.uploads[0].sha256='changed';await assert.rejects(w.submit(p,api),/已变化/);
const failed={...api,post:async()=>({status:'ready',uploads:clone(task.uploads),report:{counts:{error:1}}})};
await assert.rejects(w.prepare({taskId:'task-B'},failed),/未通过/);
const fake={...api,post:async(p)=>p.endsWith('validate')?{status:'ready',uploads:clone(task.uploads),report:{severity:'pass',counts:{error:0}}}:{...result,fallback:true}};
await assert.rejects(w.prepare({taskId:'task-B'},fake),/已停止/);
const source=fs.readFileSync('src/pages/ai-policy.jsx','utf8');
assert.ok(!source.includes("sample: 'true'"));assert.ok(!source.includes('本月共 142'));assert.ok(!source.includes('defaultValue={n.v}'));
for(const status of ['queued','pending','running'])assert.equal(w.mutable({...task,latestJob:{status}}),false);
for(const error of [undefined,null,'0'])await assert.rejects(w.prepare({taskId:task.id},{...api,post:async()=>({status:'ready',uploads:clone(task.uploads),report:{counts:{error}}})}),/未通过/);
await assert.rejects(w.prepare({taskId:task.id},{...api,post:async()=>({status:'ready',report:{counts:{error:0}}})}),/文件版本/);
await assert.rejects(w.prepare({taskId:task.id},{...api,post:async(path,b)=>path.endsWith('parse')?{...result,policyId:null}:api.post(path,b)}),/确认编号/);
const reviewed=await w.prepare({taskId:task.id},api);
let scheduleAttempts=0;
const concurrent={...api,post:async(path,b)=>{
  if(path.endsWith('validate'))task.uploads[0].sha256+='changed-during-validation';
  if(path.endsWith('schedule-jobs'))scheduleAttempts++;
  return api.post(path,b);
}};
await assert.rejects(w.submit(reviewed,concurrent),/已变化/);
assert.equal(scheduleAttempts,0);
await assert.rejects(w.prepare({taskId:task.id},concurrent),/已变化/);
const fresh=await w.prepare({taskId:task.id},api);
await assert.rejects(w.submit(fresh,{...api,post:async(path,b)=>{if(path.endsWith('schedule-jobs'))throw new Error('409 uploads changed');return api.post(path,b);}}),/409/);
await assert.rejects(w.submit(fresh,{...api,post:async(path,b)=>path.endsWith('schedule-jobs')?{}:api.post(path,b)}),/编号/);
console.log('PASS: real task workflow, explicit policy/upload binding, before/during-validation changes, failed/malformed/fallback rejection; no implicit sample or fake success.');
