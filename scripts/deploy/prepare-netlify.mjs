import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const defaultAppRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

export function validateApiOrigin(value) {
  // Match raw input before URL normalization: no silently stripped credentials,
  // whitespace, default ports, encoded paths, trailing slashes or CRLF.
  const match = typeof value === 'string'
    && /^https:\/\/([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)\.onrender\.com$/.exec(value);
  if (!match || /(?:^|-)(?:example|placeholder|changeme|change-me|replace|your|localhost)(?:-|$)/.test(match[1])) {
    throw new Error('JKXT_API_ORIGIN must be an explicit canonical HTTPS Render service origin (https://SERVICE.onrender.com), without credentials, port, path, query, fragment or placeholders.');
  }
  return value;
}

function requireDirectory(directory, label) {
  if (!fs.existsSync(directory)) throw new Error(`${label} is missing; run npm run build first.`);
  const stat = fs.lstatSync(directory);
  if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error(`${label} must be a real directory, not a symlink.`);
}

function verifyPublishTree(dist) {
  const rootFiles = new Set(['Dashboard.html', 'build-manifest.json', 'REACT-LICENSE.txt', '_redirects', '_headers']);
  const rootDirectories = new Set(['assets', 'compiled', 'src']);
  function walk(directory, relative = '') {
    for (const name of fs.readdirSync(directory)) {
      const entry = relative ? `${relative}/${name}` : name;
      const file = path.join(directory, name);
      const stat = fs.lstatSync(file);
      if (stat.isSymbolicLink()) throw new Error(`Refusing symlink in publish directory: ${entry}`);
      if (!relative && !(stat.isDirectory() ? rootDirectories : rootFiles).has(name)) {
        throw new Error(`Unexpected publish entry: ${entry}`);
      }
      if (/(^|\/)(?:\.[^/]+|node_modules|backend|credentials?|secrets?)(\/|$)/i.test(entry)
          || /\.(?:pem|key|p12|pfx|env|jks|keystore)$/i.test(entry)) {
        throw new Error(`Refusing potential secret or private publish file: ${entry}`);
      }
      if (entry.startsWith('src/') && entry !== 'src/styles' && !entry.startsWith('src/styles/')) {
        throw new Error(`Unexpected source path in publish directory: ${entry}`);
      }
      if (stat.isDirectory()) {
        if (!relative && rootFiles.has(name)) throw new Error(`Expected regular publish file: ${entry}`);
        walk(file, entry);
      } else if (!stat.isFile() || stat.nlink !== 1) {
        throw new Error(`Expected regular publish file without hardlinks: ${entry}`);
      }
    }
  }
  walk(dist);
}

function verifyBuild(dist) {
  for (const name of ['Dashboard.html', 'build-manifest.json']) {
    if (!fs.existsSync(path.join(dist, name))) throw new Error(`Required build file is missing: ${name}`);
  }
  const manifest = JSON.parse(fs.readFileSync(path.join(dist, 'build-manifest.json'), 'utf8'));
  if (manifest.schema !== 'jkxt-frontend-build/v1' || !Array.isArray(manifest.entries) || !manifest.entries.length) {
    throw new Error('Invalid frontend build manifest; run npm run build first.');
  }
  if (hash(fs.readFileSync(path.join(dist, 'Dashboard.html'))) !== manifest.htmlSha256) {
    throw new Error('Dashboard.html checksum does not match its build manifest.');
  }
  const emitted = new Set();
  for (const entry of manifest.entries) {
    if (!entry || typeof entry.output !== 'string' || !/^compiled\/[a-zA-Z0-9_-]+\.[a-f0-9]{16}\.(?:js|css)$/.test(entry.output)
        || typeof entry.sha256 !== 'string' || !/^[a-f0-9]{64}$/.test(entry.sha256)
        || !entry.output.includes(`.${entry.sha256.slice(0, 16)}.`) || emitted.has(entry.output)) {
      throw new Error('Invalid or duplicate compiled path in frontend build manifest.');
    }
    emitted.add(entry.output);
    if (hash(fs.readFileSync(path.join(dist, entry.output))) !== entry.sha256) {
      throw new Error(`Compiled asset checksum mismatch: ${entry.output}`);
    }
  }
  for (const name of fs.readdirSync(path.join(dist, 'compiled'))) {
    if (!emitted.has(`compiled/${name}`)) throw new Error(`Unexpected compiled publish file: ${name}`);
  }
}

function redirects(origin) {
  return [
    '# Generated by prepare-netlify.mjs; backend status/body are passed through.',
    `/api/v1 ${origin}/api/v1 200!`,
    `/api/v1/* ${origin}/api/v1/:splat 200!`,
    '# Only the existing root entry is rewritten. Query portal selection stays in the browser URL.',
    '/ /Dashboard.html 200',
    '# No global HTML fallback: missing assets and unknown non-v1 API paths remain 404.',
    '',
  ].join('\n');
}

const staticHeaders = [
  '# Applies to static files only; Render must supply API cache/security headers.',
  '/*',
  '  X-Content-Type-Options: nosniff',
  '  X-Frame-Options: DENY',
  '  Referrer-Policy: strict-origin-when-cross-origin',
  "  Content-Security-Policy: frame-ancestors 'none'; base-uri 'self'; object-src 'none'",
  '/',
  '  Cache-Control: no-store',
  '/Dashboard.html',
  '  Cache-Control: no-store',
  '/build-manifest.json',
  '  Cache-Control: no-store',
  '/compiled/*',
  '  Cache-Control: public, max-age=31536000, immutable',
  '/assets/*',
  '  Cache-Control: public, max-age=300, must-revalidate',
  '/src/styles/*',
  '  Cache-Control: no-cache',
  '',
].join('\n');

export function prepareNetlify({ appRoot = defaultAppRoot, apiOrigin = process.env.JKXT_API_ORIGIN } = {}) {
  const origin = validateApiOrigin(apiOrigin);
  const root = path.resolve(appRoot);
  requireDirectory(root, 'Application root');
  // Fixed output only. The CLI has no path overrides and never removes a tree.
  const dist = path.join(root, 'dist');
  requireDirectory(dist, 'dist');
  if (fs.realpathSync(dist) !== path.join(fs.realpathSync(root), 'dist')) {
    throw new Error('dist resolves outside the application root.');
  }
  verifyPublishTree(dist);
  verifyBuild(dist);
  const files = { _redirects: redirects(origin), _headers: staticHeaders };
  for (const [name, content] of Object.entries(files)) {
    const temporary = path.join(dist, `${name}.${crypto.randomUUID()}.tmp`);
    try {
      fs.writeFileSync(temporary, content, { encoding: 'utf8', flag: 'wx' });
      fs.renameSync(temporary, path.join(dist, name));
    } finally {
      // Only a unique file created immediately above, never user-supplied paths.
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
    }
  }
  return { publishDirectory: dist, apiOrigin: origin, files: Object.keys(files) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 2) throw new Error('No CLI arguments are accepted; output is fixed to this application dist directory.');
    const result = prepareNetlify();
    console.log(`Prepared Netlify static deployment: ${result.files.join(', ')}; API proxy origin validated.`);
  } catch (error) {
    console.error(`Netlify preparation failed: ${error.message}`);
    process.exitCode = 1;
  }
}
